internal sealed class TraditionalChineseEnumConverter : IValueConverter
{
    public object Convert(object value, Type targetType, object parameter, CultureInfo culture) =>
        value is Enum enumValue ? UiDisplayText.Enum(enumValue) : value;

    public object ConvertBack(object value, Type targetType, object parameter, CultureInfo culture) =>
        value is string text && UiDisplayText.TryParseEnum(targetType, text.Trim(), out var parsed)
            ? parsed!
            : DependencyProperty.UnsetValue;
}
