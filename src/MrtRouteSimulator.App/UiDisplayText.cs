    public static string Boolean(bool value) => value ? "是" : "否";

    public static bool TryParseBoolean(string text, out bool value)
    {
        if (text.Equals("是", StringComparison.OrdinalIgnoreCase) || bool.TryParse(text, out value) && value)
        {
            value = true;
            return true;
        }

        if (text.Equals("否", StringComparison.OrdinalIgnoreCase) || bool.TryParse(text, out value) && !value)
        {
            value = false;
            return true;
        }

        value = false;
        return false;
    }

    public static bool TryParseEnum(Type targetType, string text, out object? value)
    {
        foreach (var candidate in System.Enum.GetValues(targetType).Cast<Enum>())
        {
            if (string.Equals(text, Enum(candidate), StringComparison.OrdinalIgnoreCase)
                || string.Equals(text, candidate.ToString(), StringComparison.OrdinalIgnoreCase))
            {
                value = candidate;
                return true;
            }
        }

        value = null;
        return false;
    }
